// 시도 표준 목록 — 홈의 `지역으로 찾기`가 데이터에 없는 지역까지 전부 보여주기 위한 기준
//
// **왜 데이터가 아니라 목록을 기준으로 삼는가.** `collectRegionCounts`는 **데이터에
// 등장하는 지역만** 돌려준다. 그러면 수록 교회가 0인 지역은 화면에서 아예 사라지고,
// 사용자는 **"빠뜨린 건지 아직 없는 건지"를 구분할 수 없다.** 전체를 세워 두고 0을
// 그대로 보여주는 편이 정직하다 — `notices.json`이 지켜온 방식과 같다.
//
// ⚠️ **17개가 아니라 16개다.** 도로명주소 API가 돌려준 주소가 `전남광주통합특별시`라
// 전남과 광주가 통합돼 있다(`강원특별자치도`·`전북특별자치도`도 같은 자료에서 확인된다).
// **정부가 통합한 단위를 화면에서 도로 쪼개지 않는다.**
//
// **`전남광주`는 옛 전남 자리에 둔다.** 표준 순서에서 광주는 인천과 대전 사이지만,
// 짧은 표기가 `전남`으로 시작하고 지리적으로도 전북 다음이 자연스럽다.

/**
 * 행정구역 표준 순서. **건수 순이 아니다.**
 *
 * ⚠️ **건수 내림차순으로 되돌리지 말 것.** 그러면 지역에 서열이 생기는데,
 * `/about`이 **"노출 순서에 어떤 평가도 반영하지 않습니다"**라고 화면에 적어 두고
 * 있다. 표준 순서는 **한국인이 이미 아는 고정 순서**라 자기 지역이 몇 번째 줄에
 * 있는지 예측할 수 있다는 실용적 이점도 있다 — 16칸을 훑을 때 이게 결정적이다.
 *
 * 값은 `churches.json`의 `region` 필드와 같은 짧은 표기다.
 */
export const STANDARD_REGIONS = [
  "서울",
  "부산",
  "대구",
  "인천",
  "대전",
  "울산",
  "세종",
  "경기",
  "강원",
  "충북",
  "충남",
  "전북",
  "전남광주",
  "경북",
  "경남",
  "제주",
] as const;

/**
 * 홈 h1의 지역 롤링에 굴릴 지역을 뽑는다 (2026-09-13).
 *
 * ⚠️ **예전에는 `건수 상위 N`이었다. 그 방식으로 되돌리지 말 것.**
 * 15개 지역 중 **10개가 아예 후보에 들어가지 못했고**(충북·전남광주·대구·세종·경북·
 * 충남·강원·대전·울산·경남), 무엇보다 **충북·부산·인천이 똑같이 4곳인데 부산·인천만
 * 뽑혀** 동점을 임의로 잘랐다. 지역 칩에서 `건수 순위를 노출하지 않는다`로 정리해
 * 놓고 **바로 위 h1만 상위 5를 전시하고 있었다.**
 *
 * **무작위 표본이다.** 홈은 `revalidate`로 15분마다 다시 구워지므로 표본도 그때
 * 바뀐다 — 오래 보면 모든 지역이 고르게 나온다. 홈 미리보기 교회를 무작위로 뽑는
 * 것과 **같은 방식이고 같은 주기**다.
 *
 * ⚠️ **전체를 돌리지 않는 이유.** `globals.css`의 키프레임이 **항목 수에 비례한
 * 퍼센트**로 각 항목의 노출 구간을 잡는다(5칸 기준). 15개를 돌리려면 항목 수마다
 * 키프레임을 따로 써야 하고, 늘어날 때마다 CSS를 고쳐야 한다. 그렇게 해도
 * **2초 × 15개 = 30초 주기**라 **한 방문자가 보는 개수는 지금과 별로 다르지 않다** —
 * 비용은 크고 얻는 것은 작다.
 *
 * **뽑은 뒤 표준 순서로 되돌린다.** 굴러가는 차례가 뒤죽박죽이면 임의로 보인다.
 */
export function sampleRegions(regions: string[], count: number): string[] {
  const pool = [...regions];
  const take = Math.min(count, pool.length);

  // Fisher–Yates를 앞 `take`칸만 돌린다 — `getPreviewChurches`와 같은 방식이다
  for (let i = 0; i < take; i++) {
    const j = i + Math.floor(Math.random() * (pool.length - i));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }

  const picked = new Set(pool.slice(0, take));
  return STANDARD_REGIONS.filter((region) => picked.has(region));
}
